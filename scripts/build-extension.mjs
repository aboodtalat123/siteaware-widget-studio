import { cp, mkdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { execSync } from 'node:child_process';

const root = process.cwd();
const distDir = path.join(root, 'dist');
const targetDir = path.join(distDir, 'extension');

await mkdir(distDir, { recursive: true });

// Step 1: Copy static extension files first
console.log('Copying static extension files...');
await rm(targetDir, { recursive: true, force: true });
await cp(path.join(root, 'extension'), targetDir, { recursive: true });

// Step 1b: Prune legacy/non-canonical artifacts from the BUILT extension
// only (source backups are never touched). The unpacked product must be
// exactly one Unified Extension: no legacy sidepanel.js wiring, no
// manual-token UI, no *.backup/*.bak files.
for (const legacy of [
  'sidepanel.js',
  'sidepanel.html.legacy-backup',
  'sidepanel.html.backup',
]) {
  await rm(path.join(targetDir, legacy), { force: true });
}
{
  const { readdir } = await import('node:fs/promises');
  for (const entry of await readdir(targetDir)) {
    if (entry.endsWith('.backup') || entry.endsWith('.bak')) {
      await rm(path.join(targetDir, entry), { force: true });
    }
  }
}

// Step 2: Run Vite build with extension config to produce sidepanel-bundle.js and CSS
console.log('Running Vite build for extension...');
execSync('vite build --config vite.config.extension.ts', { cwd: root, stdio: 'inherit' });

// Step 3: Inject REAL build metadata into dist/extension/build-info.js
// Literal values from actual git/build state — never placeholders.
try {
  const sha = execSync('git rev-parse --short HEAD', { encoding: 'utf8' }).trim();
  const branch = execSync('git branch --show-current', { encoding: 'utf8' }).trim() || 'detached';
  const buildId = `b${Date.now().toString(36)}${Math.floor(Math.random() * 1296).toString(36).padStart(2, '0')}`;
  const content = `// Build-time injected information (real values, generated by scripts/build-extension.mjs)\n\nexport const BUILD_INFO = {\n  branch: '${branch}',\n  sha: '${sha}',\n  id: '${buildId}',\n};\n`;
  await writeFile(path.join(targetDir, 'build-info.js'), content, 'utf8');
  console.log(`build-info: branch=${branch} sha=${sha} id=${buildId}`);
} catch (error) {
  console.error(`build-info injection failed: ${error instanceof Error ? error.message : error}`);
  throw error;
}

console.log(`Built extension to ${targetDir}`);
